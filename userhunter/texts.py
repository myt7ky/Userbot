def plural(n: int, one: str, few: str, many: str) -> str:
    n100, n10 = abs(n) % 100, abs(n) % 10
    if 10 < n100 < 20:
        return many
    if n10 == 1:
        return one
    if 2 <= n10 <= 4:
        return few
    return many


def searches(n: int) -> str:
    return f"{n} {plural(n, 'поиск', 'поиска', 'поисков')}"


